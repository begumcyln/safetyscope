"""Investigate alert numbers, reporting years, publication dates and measure dates.

Usage:
    python src/investigate_dates.py     (after src/pipeline.py)

Writes reports/date_investigation.md. Every number is computed here.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import pandas as pd  # noqa: E402

from profile_data import md_table  # noqa: E402
from safetyscope import config as C  # noqa: E402


def main() -> None:
    a = pd.read_csv(C.PROCESSED_DIR / "alerts_clean.csv", low_memory=False,
                    parse_dates=["publication_date", "weekly_report_date", "first_measure_date"])
    m = pd.read_csv(C.PROCESSED_DIR / "alert_measures.csv", parse_dates=["entry_into_force_date"])
    a["report_year"] = a["weekly_report_date"].dt.year
    a["publication_year"] = a["publication_date"].dt.year
    a["pub_minus_report_days"] = (a["publication_date"] - a["weekly_report_date"]).dt.days
    a["report_minus_measure_days"] = (a["weekly_report_date"] - a["first_measure_date"]).dt.days

    R = []
    w = R.append
    w("# Date and Identifier Investigation\n")
    w("*Generated by `src/investigate_dates.py`.*\n")
    w("## Question\n")
    w("The export was downloaded with a 2025 filter, yet alert numbers end in `/20`, `/24` and `/25`. "
      "Which date does the filter use, and what do the different dates mean?\n")
    w("## Evidence sources\n")
    w("1. **Excel export** - alert number only; no date columns.")
    w("2. **Official Safety Gate XML weekly reports** (public download, "
      "`https://ec.europa.eu/safety-gate-alerts/api/download/weeklyReport/list/xml/en`). Each weekly report has a "
      "`report_date` (a Friday) and each alert in it has its own `publicationDate`. Reports for 2020 and 2024-2026 were downloaded.")
    w("3. **Measure text** - 'Date of entry into force' of each corrective measure.")
    w("4. **Official Safety Gate disclaimer** (PDF linked from the portal footer): information in alerts is provided by the national contact points; "
      "the Commission is not liable for its accuracy. No official definition of the alert-number format or of `publicationDate` was found in readable official pages.\n")

    w("## Findings (verified from the data)\n")
    w("### 1. Alert-number year vs weekly-report year\n")
    w(md_table(pd.crosstab(a["alert_number_year"], a["report_year"], margins=True, margins_name="Total"), index=True))
    w("")
    w("### 2. Alert-number year vs alert publicationDate year\n")
    w(md_table(pd.crosstab(a["alert_number_year"], a["publication_year"], margins=True, margins_name="Total"), index=True))
    w("")
    lag = a["pub_minus_report_days"]
    w("### 3. publicationDate is not the same as the weekly report date\n")
    w(f"- publicationDate **before or on** the weekly report date: {int((lag <= 0).sum())} alerts "
      f"(median {lag[lag <= 0].median():.0f} days before; publication normally precedes the Friday report).")
    w(f"- publicationDate **after** the weekly report date: {int((lag > 0).sum())} alerts (up to {int(lag.max())} days after).")
    late = a.loc[lag > 30, ["alert_number", "weekly_report", "weekly_report_date", "publication_date", "pub_minus_report_days"]]
    late = late.sort_values("pub_minus_report_days", ascending=False)
    late["weekly_report_date"] = late["weekly_report_date"].dt.date
    late["publication_date"] = late["publication_date"].dt.date
    w(f"\nAlerts whose publicationDate is more than 30 days after their weekly report ({len(late)}):\n")
    w(md_table(late))
    w("\nThe most extreme case is `A12/01220/20`: listed in weekly report **Report-2020-37** (11 Sep 2020), but its XML "
      "publicationDate is **14 May 2025**.\n")

    w("### 4. Which rule reproduces the export?\n")
    rec = pd.read_csv(C.REPORTS_DIR / "tables" / "export_vs_xml_reconciliation.csv")
    w(md_table(rec))
    w("\nThe rule *'weekly report in 2025 **or** publicationDate in 2025'* accounts for **every** exported record. "
      "Two cosmetics alerts that satisfy this rule are absent from the export (`SR/01873/25`, `SR/03775/24`). "
      "`SR/01873/25` was checked on the live portal on 27 Nov 2026: it is a Cosmetics alert published 15/05/2025. "
      "Why it was not exported is unknown.\n")

    w("### 5. Measure dates are much earlier than publication\n")
    md = a["report_minus_measure_days"].dropna()
    w(f"- Alerts with at least one dated measure: {len(md)} of {len(a)}.")
    w(f"- Median time from the first measure's entry into force to the weekly report: **{md.median():.0f} days** "
      f"(25th percentile {md.quantile(.25):.0f}, 75th percentile {md.quantile(.75):.0f}).")
    by_year = m.dropna(subset=["entry_into_force_date"]).groupby(m["entry_into_force_date"].dt.year)["alert_number"].nunique()
    w("- Alerts by year of measure entry into force: " + ", ".join(f"{int(k)}: {v}" for k, v in by_year.items()) + ".\n")

    w("## Interpretation (hypotheses, not verified facts)\n")
    w("- **H1 - the alert-number suffix is the year the notification was registered**, not the publication year. "
      "Consistent with: no alert appears in a weekly report dated before its suffix year, and `/24` alerts appear in 2024 or 2025 reports; "
      "but not confirmed by official documentation.")
    w("- **H2 - XML `publicationDate` reflects the latest (re-)publication or update of an alert**, not its first publication. "
      "Consistent with: publicationDates months after the weekly report the alert first appeared in. "
      "Not confirmed by official documentation.")
    w("- **H3 - the portal's year filter matches either the weekly report year or the alert's (latest) publication year.** "
      "This reproduces 1,714 of 1,714 exported records, but also predicts 2 records that were not exported, so the rule is not exact.")
    w("- **H4 - corrective measures usually precede publication by months**, because national authorities notify after their own "
      "market-surveillance action and the alert is validated before publication.\n")

    w("## Consequences for the analysis\n")
    w("- **Time series use the weekly report date** (first appearance in the official weekly report). It exists for every alert and is one consistent definition.")
    w("- Alert-number year, publicationDate and measure dates are kept as separate columns and never mixed.")
    w("- The dataset is described as *'cosmetics alerts selected by the portal's 2025 filter'*, not as *'all alerts notified in 2025'*.")
    w("- Week-level trends reflect when authorities' notifications were published, not when unsafe products were placed on the market.\n")

    w("## Open questions for manual review\n")
    w("- Record the portal's on-screen result count next time an export is downloaded (it was not saved for this export).")
    w("- Ask the Safety Gate helpdesk (or check updated documentation) for the official definition of the alert-number suffix and of `publicationDate`.")
    w("- Check why `SR/01873/25` and `SR/03775/24` are not in the export.\n")

    out = C.REPORTS_DIR / "date_investigation.md"
    out.write_text("\n".join(R), encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
