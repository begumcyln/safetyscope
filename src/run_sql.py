"""Run every query in sql/business_queries.sql and save the results.

Usage:
    python src/run_sql.py

Writes reports/sql_results.md (question, SQL and result table per query) and
reports/tables/sql_<name>.csv. Fails loudly if any query errors.
"""

from __future__ import annotations

import re
import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import pandas as pd  # noqa: E402

from profile_data import md_table  # noqa: E402
from safetyscope import config as C  # noqa: E402

QUERY_FILE = C.ROOT / "sql" / "business_queries.sql"


def parse_queries(text: str) -> list[dict]:
    """Split the file on '-- name:' markers."""
    queries = []
    for block in re.split(r"(?m)^-- name: ", text)[1:]:
        name, rest = block.split("\n", 1)
        question = re.search(r"(?m)^-- question: (.+)$", rest)
        sql = "\n".join(line for line in rest.splitlines() if not line.startswith("-- question:")).strip()
        queries.append({"name": name.strip(), "question": question.group(1).strip() if question else "", "sql": sql})
    return queries


def run_all() -> dict[str, pd.DataFrame]:
    con = sqlite3.connect(C.DB_PATH)
    results = {}
    try:
        for q in parse_queries(QUERY_FILE.read_text()):
            results[q["name"]] = (q, pd.read_sql_query(q["sql"], con))
    finally:
        con.close()
    return results


def main() -> None:
    out_dir = C.REPORTS_DIR / "tables"
    out_dir.mkdir(parents=True, exist_ok=True)
    results = run_all()
    R = ["# SQL Business Queries - Results\n",
         "*Generated by `src/run_sql.py` from `sql/business_queries.sql` against `data/processed/safetyscope.db`.*\n",
         "Unit of every count: one Safety Gate alert (notification). Counts are not defect rates, market shares or safety rankings.\n"]
    for name, (q, df) in results.items():
        df.to_csv(out_dir / f"sql_{name}.csv", index=False)
        R.append(f"## {name}\n\n**Question:** {q['question']}\n")
        R.append("<details><summary>SQL</summary>\n\n```sql\n" + q["sql"] + "\n```\n</details>\n")
        R.append(md_table(df) + "\n")
    (C.REPORTS_DIR / "sql_results.md").write_text("\n".join(R), encoding="utf-8")
    print(f"{len(results)} queries ran successfully -> reports/sql_results.md")


if __name__ == "__main__":
    main()
