"""Stage B - document what the ETL pipeline changed, why, and how many records.

Usage:
    python src/cleaning_report.py       (after src/pipeline.py)

Writes reports/cleaning_report.md and data/processed/data_quality_issues.csv.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import pandas as pd  # noqa: E402

from profile_data import md_table  # noqa: E402
from safetyscope import config as C  # noqa: E402
from safetyscope.extract import read_export  # noqa: E402
from safetyscope.standardize import normalize_text  # noqa: E402


def main() -> None:
    raw = read_export(C.RAW_EXPORT)
    a = pd.read_csv(C.PROCESSED_DIR / "alerts_clean.csv", low_memory=False,
                    parse_dates=["publication_date", "weekly_report_date", "first_measure_date"])
    m = pd.read_csv(C.PROCESSED_DIR / "alert_measures.csv", parse_dates=["entry_into_force_date"])
    s = pd.read_csv(C.PROCESSED_DIR / "alert_substances.csv")
    cand = pd.read_csv(C.PROCESSED_DIR / "substance_candidates_uncertain.csv")
    summary = json.loads((C.PROCESSED_DIR / "pipeline_run_summary.json").read_text())
    n = len(a)

    # Whitespace / encoding: count cells whose value changed
    ws_rows = []
    for col in [c for c in raw.columns if c not in ("source_row", "source_file", "Compulsory measures", "Voluntary measures")]:
        orig = raw[col]
        new = orig.map(normalize_text)
        changed = int(((orig.fillna("") != new.fillna("")) & orig.notna()).sum())
        if changed:
            ws_rows.append({"column": col, "cells_changed": changed})
    ws = pd.DataFrame(ws_rows).sort_values("cells_changed", ascending=False)

    prod_changed = int((raw["Product"].values != a["product_type"].values).sum())
    prod_changed_beyond_ws = int((raw["Product"].map(normalize_text).values != a["product_type"].values).sum())
    origin_relabelled = int((a["origin_country_raw"] != a["origin_country"]).sum())
    notifier_relabelled = int((a["notifying_country_raw"] != a["notifying_country"]).sum())
    brand_changed = int(((a["brand_raw"].map(normalize_text) != a["brand"]) & a["brand_raw"].notna()).sum())
    brand_groups = (a.dropna(subset=["brand_key"]).groupby("brand_key")["brand_raw"].nunique())
    merged_brand_groups = brand_groups[brand_groups > 1]
    legal_changed = int((a["legal_provision_raw"].map(normalize_text) != a["legal_provision"]).sum())

    # Data quality issues (records are kept and flagged, never silently fixed)
    issues = []
    for r in a[a["brand_raw"].isna()].itertuples():
        issues.append((r.alert_number, "brand_missing", "Brand is empty in the source"))
    for r in a[a["product_name_raw"].isna()].itertuples():
        issues.append((r.alert_number, "product_name_missing", "Name is empty in the source"))
    unknown_dates = m[m["entry_into_force_raw"].eq("Unknown")]
    for r in unknown_dates.itertuples():
        issues.append((r.alert_number, "measure_date_unknown", f"{r.measure_kind} measure '{r.measure_category}' has date 'Unknown'"))
    mm = m.merge(a[["alert_number", "weekly_report_date"]], on="alert_number")
    after = mm[mm["entry_into_force_date"] > mm["weekly_report_date"]]
    for r in after.itertuples():
        issues.append((r.alert_number, "measure_after_report",
                       f"Measure entry into force {r.entry_into_force_date.date()} is after weekly report date {r.weekly_report_date.date()}"))
    no_sub = a[a["primary_substance"].isna()]
    for r in no_sub.itertuples():
        issues.append((r.alert_number, "no_substance_extracted", "Risk text names no substance/agent in the dictionary"))
    for r in cand.itertuples():
        issues.append((r.alert_number, "uncertain_candidate", f"Unrecognised candidate: '{r.candidate_text}'"))
    unc = s[s["confidence"].eq("uncertain")]
    for r in unc.itertuples():
        issues.append((r.alert_number, "uncertain_substance", f"Hedged mention: {r.substance}"))
    issues_df = pd.DataFrame(issues, columns=["alert_number", "issue_type", "detail"])
    issues_df.to_csv(C.PROCESSED_DIR / "data_quality_issues.csv", index=False)

    R = []
    w = R.append
    w("# Cleaning Report (Stage B)\n")
    w("*Generated by `src/cleaning_report.py` from the outputs of `src/pipeline.py`.*\n")
    w(f"- Pipeline run: {summary['run_started_utc']} (UTC)")
    w(f"- Input: `{summary['source_files'][0]['file']}` - {summary['source_files'][0]['rows']} rows, SHA-256 `{summary['source_files'][0]['sha256'][:16]}...`")
    w(f"- Output: {n} alerts in `data/processed/alerts_clean.csv` (no rows removed) plus bridge tables.\n")
    w("**Principle:** no source value is overwritten. Every cleaned column sits next to a `*_raw` column with the original value, "
      "and the untouched export is also stored in the database table `raw_export`.\n")

    w("## Summary of transformations\n")
    steps = pd.DataFrame([
        ("Column names", "Converted to snake_case (e.g. `Alert submitted by` -> `notifying_country`)", "Readable, code-friendly names", "all 25 columns"),
        ("Whitespace & encoding", "Unicode NFC, non-breaking spaces replaced, repeated spaces/line breaks collapsed, trimmed",
         "Invisible differences split identical values into separate categories", f"{int(ws['cells_changed'].sum())} cells in {len(ws)} columns"),
        ("Missing values", "Kept as missing (no imputation). `Counterfeit`, `Country of origin` keep the source value 'Unknown' as a category",
         "Imputing brands or names would fabricate data", f"Brand missing: {int(a['brand_raw'].isna().sum())}; Name missing: {int(a['product_name_raw'].isna().sum())}"),
        ("Alert ID validation", "Pattern `PREFIX/NNNNN/YY` checked; prefix, sequence, year suffix and case ID extracted",
         "Detect malformed IDs; enable year analysis", f"{int(a['alert_number_valid'].sum())} of {n} valid; 0 duplicates"),
        ("Duplicates", "Checked exact rows, alert numbers and case URLs; near-duplicates flagged, not removed",
         "Same product can be notified several times legitimately", "0 removed"),
        ("Product names", "Case/spacing normalised, spelling variants merged (explicit list), project product group added",
         "`Shower gel`/`shower gel` were counted separately", f"{prod_changed} records changed ({prod_changed_beyond_ws} beyond whitespace); 231 -> {a['product_type'].nunique()} types"),
        ("Country names", "Safety Gate labels mapped to display names + ISO2 + EU flag",
         "Shorter labels, joinable with other data", f"origin relabelled: {origin_relabelled}; notifier relabelled: {notifier_relabelled}"),
        ("Brand names", "Case-, accent- and punctuation-insensitive key; most frequent spelling used as display name",
         "`PARFUMS DE QUALITE'` vs `Parfums de Qualité`", f"{brand_changed} records got a different display spelling; {len(merged_brand_groups)} brands had >1 spelling"),
        ("Legal provision", "Trailing full stop removed, `Cosmetic Product Regulation` -> `Cosmetic Products Regulation`",
         "21 variants of mostly the same sentence", f"{legal_changed} records; 21 -> {a['legal_provision'].nunique()} variants"),
        ("Risk types (multivalued)", "Split on comma into `alert_risk_types`", "Count each risk without double counting", f"{int((a['risk_type_count'] > 1).sum())} alerts with 2 risk types"),
        ("Corrective measures", "Measure blocks parsed into operator, category, group and date", "Free text -> analysable fields",
         f"{len(m)} measures from {m['alert_number'].nunique()} alerts; {int((~m['parsed_ok']).sum())} parse failures"),
        ("Dates", "Measure dates parsed (dd/mm/yyyy); weekly report and publication dates added from official XML",
         "Export has no date column", f"{int(m['entry_into_force_date'].notna().sum())} measure dates parsed, {int(m['entry_into_force_raw'].eq('Unknown').sum())} 'Unknown'; {int(a['xml_matched'].sum())} alerts matched to XML"),
        ("Substances", "Rule-based extraction from risk text (Stage C)", "Main analytical dimension",
         f"{len(s)} mentions in {s['alert_number'].nunique()} alerts"),
    ], columns=["step", "what changed", "why", "records affected"])
    w(md_table(steps))

    w("\n## Whitespace / encoding changes by column\n")
    w(md_table(ws))
    w("\n## Brands with more than one spelling (merged)\n")
    ex = (a[a["brand_key"].isin(merged_brand_groups.index)].groupby("brand")["brand_raw"]
          .agg(lambda x: " / ".join(sorted(set(x)))).reset_index().rename(columns={"brand_raw": "original spellings"}))
    w(md_table(ex, max_rows=25))
    w(f"\n({len(ex)} brands in total; full mapping in `data/reference/brand_mapping.csv`.) Brand matching is deliberately conservative: "
      "brands that differ in more than case, accents or punctuation (e.g. with/without 'Paris') are **not** merged.\n")

    w("## Data quality issues (flagged, not fixed)\n")
    w(md_table(issues_df["issue_type"].value_counts().rename_axis("issue_type").reset_index(name="records")))
    w("\nRow-level list: `data/processed/data_quality_issues.csv`.\n")
    if len(after):
        w(f"**Measures dated after the weekly report:** {len(after)} measures in {after['alert_number'].nunique()} alerts have an entry-into-force date "
          "later than the weekly report in which the alert appeared. Possible reasons: measures added in later updates of the alert, or data-entry errors. They are kept as recorded.\n")

    w("## Remaining uncertainties\n")
    w("- The meaning of the alert-number suffix and of the XML `publicationDate` is inferred, not officially documented (see `date_investigation.md`).")
    w("- Product groups are a project-defined classification; borderline products (e.g. `Hair and body cream`, `Shower foam and deodorant`) were assigned by first matching rule.")
    w("- Brand normalisation cannot detect different brands with the same name, or counterfeit use of a brand name (the official disclaimer warns about this).")
    w("- `Unknown` country of origin (267 alerts) means the origin was not established by the notifying authority; these alerts are excluded only from origin-specific percentages, and this is always stated.")
    w("- The substance dictionary was built from the texts in this export; new alerts may name substances it does not contain. These surface as 'uncertain candidates'.")

    out = C.REPORTS_DIR / "cleaning_report.md"
    out.write_text("\n".join(R), encoding="utf-8")
    print(f"Wrote {out}; {len(issues_df)} issues flagged")


if __name__ == "__main__":
    main()
